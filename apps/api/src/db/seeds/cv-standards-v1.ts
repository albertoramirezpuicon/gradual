export const CV_STANDARDS_V1 = `# Estándares para mejorar un CV

## Objetivo
Un CV claro, honesto y orientado a resultados, que una persona reclutadora entienda en menos de 30 segundos y que los sistemas de selección (ATS) puedan leer sin problemas.

## Estructura y orden
1. Datos de contacto: nombre completo, ciudad, teléfono, correo profesional y LinkedIn (si tiene). No incluir DNI, fecha de nacimiento, estado civil ni fotografía.
2. Titular profesional: una línea con el rol al que apunta (por ejemplo, "Analista de Marketing Digital").
3. Perfil profesional: 3 a 4 líneas con años de experiencia, especialidad, 2 o 3 fortalezas y el tipo de puesto que busca.
4. Experiencia laboral: de la más reciente a la más antigua. Para cada puesto: cargo, empresa, ciudad y fechas (mes/año).
5. Educación: grado, institución y fechas. Incluir cursos relevantes solo si aportan al objetivo.
6. Habilidades: técnicas y herramientas concretas (no rasgos genéricos como "proactivo").
7. Idiomas con nivel (básico, intermedio, avanzado, nativo).
8. Certificaciones y otros (voluntariado, proyectos) solo si suman.

## Cómo escribir la experiencia
- Entre 3 y 5 viñetas por puesto, empezando con un verbo de acción en pasado (lideré, implementé, reduje, aumenté, coordiné).
- Priorizar logros sobre funciones: qué cambió gracias a la persona.
- Cuantificar siempre que sea posible (%, montos en S/, tiempos, cantidad de personas o clientes).
- Si no hay una cifra en el CV original, no inventarla: dejar un marcador para que la persona la complete.
- Eliminar frases vacías ("responsable de", "encargado de", "trabajo en equipo").

## Estilo
- Español neutro y profesional, frases cortas, sin primera persona en las viñetas.
- Máximo 2 páginas; 1 página si tiene menos de 5 años de experiencia.
- Fechas en un formato uniforme (por ejemplo, "mar. 2022 – actualidad").
- Sin faltas de ortografía ni mayúsculas innecesarias.

## Criterios para el puntaje (0 a 100)
- Claridad y estructura: 25
- Logros y cuantificación: 30
- Redacción y ortografía: 20
- Relevancia para el objetivo profesional: 15
- Compatibilidad con ATS (formato simple, sin tablas ni gráficos, palabras clave del rol): 10
`;
